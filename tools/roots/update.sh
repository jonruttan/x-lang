#!/bin/sh
# update.sh -- regenerate lib/x/net/mozilla-roots.pem from Mozilla's list.
#
#   sh tools/roots/update.sh [CERTDATA]
#
# The trusted roots x's TLS client checks a server's chain against are
# Mozilla's: the certificates in NSS's certdata.txt whose trust object
# says CKT_NSS_TRUSTED_DELEGATOR for server authentication.  With no
# argument the file is fetched from the NSS repository; a path reads a
# copy already on disk.  Each root is written as a PEM block after two
# comment lines, its label and its subject's DER bytes in hex, which is
# what lib/x/net/roots.x searches by: a root is found by the issuer a
# certificate names without any certificate being parsed.
set -eu

here=$(cd "$(dirname "$0")" && pwd)
out="$here/../../lib/x/net/mozilla-roots.pem"
url="https://hg.mozilla.org/projects/nss/raw-file/tip/lib/ckfw/builtins/certdata.txt"

if [ $# -gt 0 ]; then
	src="$1"
else
	src=$(mktemp)
	trap 'rm -f "$src"' EXIT
	curl -sSfL -o "$src" "$url"
fi

rev=$(grep -m1 'CVS_ID\|Revision' "$src" 2>/dev/null || true)

LC_ALL=C awk -v fetched="$(date -u +%Y-%m-%d)" -v url="$url" '
function octal_bytes(line,    n, i, parts, k) {
	# "\060\202\005" -> bytes appended to buf[], nbuf the count
	n = split(line, parts, "\\")
	for (i = 2; i <= n; i++) {
		k = substr(parts[i], 1, 3)
		buf[nbuf++] = (substr(k,1,1) * 64) + (substr(k,2,1) * 8) + substr(k,3,1)
	}
}
function hex(    i, s) {
	s = ""
	for (i = 0; i < nbuf; i++) s = s sprintf("%02x", buf[i])
	return s
}
function b64(    i, s, a, b, c, n) {
	s = ""
	for (i = 0; i < nbuf; i += 3) {
		a = buf[i]; b = (i + 1 < nbuf) ? buf[i+1] : 0; c = (i + 2 < nbuf) ? buf[i+2] : 0
		n = a * 65536 + b * 256 + c
		s = s substr(B64, int(n / 262144) % 64 + 1, 1) substr(B64, int(n / 4096) % 64 + 1, 1)
		s = s ((i + 1 < nbuf) ? substr(B64, int(n / 64) % 64 + 1, 1) : "=")
		s = s ((i + 2 < nbuf) ? substr(B64, n % 64 + 1, 1) : "=")
	}
	return s
}
BEGIN {
	B64 = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
	cls = ""; field = ""
}
/^CKA_CLASS CK_OBJECT_CLASS / { cls = $3; label = ""; next }
/^CKA_LABEL UTF8 / { label = substr($0, index($0, "\"")); next }
/^CKA_(VALUE|SUBJECT) MULTILINE_OCTAL/ {
	if (cls == "CKO_CERTIFICATE") { field = $1; nbuf = 0; delete buf }
	next
}
field != "" && /^END/ {
	if (field == "CKA_VALUE") cert[label] = b64()
	else subj[label] = hex()
	field = ""; next
}
field != "" { octal_bytes($0); next }
/^CKA_TRUST_SERVER_AUTH CK_TRUST CKT_NSS_TRUSTED_DELEGATOR/ {
	if (cls == "CKO_NSS_TRUST") trusted[label] = 1
	next
}
/^CKA_CLASS/ { next }
END {
	print "# mozilla-roots.pem -- the roots x'"'"'s TLS client trusts to identify a server."
	print "#"
	print "# Generated by tools/roots/update.sh from Mozilla'"'"'s certdata.txt (NSS),"
	print "# " url
	print "# fetched " fetched ": every certificate whose trust for server"
	print "# authentication is CKT_NSS_TRUSTED_DELEGATOR.  The data is Mozilla'"'"'s,"
	print "# under the Mozilla Public License 2.0.  Do not edit; run the tool."
	print "#"
	print "# Each root follows its label and its subject'"'"'s DER bytes in hex."
	n = 0
	for (l in trusted) if (l in cert) order[++n] = l
	# a stable order: by label
	for (i = 2; i <= n; i++) { v = order[i]; j = i - 1; while (j > 0 && order[j] > v) { order[j+1] = order[j]; j-- } order[j+1] = v }
	for (i = 1; i <= n; i++) {
		l = order[i]
		print ""
		print "# Label: " l
		print "# Subject: " subj[l]
		print "-----BEGIN CERTIFICATE-----"
		s = cert[l]
		for (k = 1; k <= length(s); k += 64) print substr(s, k, 64)
		print "-----END CERTIFICATE-----"
	}
}' "$src" > "$out.tmp"
mv "$out.tmp" "$out"
echo "update.sh: $(grep -c '^-----BEGIN CERTIFICATE' "$out") roots written to lib/x/net/mozilla-roots.pem"
